"""Convert Slot's 48 kHz signed-16 mono insert PCM to GBA signed-8 mono.
The original duration is preserved with a low-pass windowed-sinc resampler.
No eject clip is used by the kernel. Run once after changing the source asset.
"""
from pathlib import Path
import math,struct,wave,json,hashlib
ROOT=Path(__file__).resolve().parents[1]
def resample(pcm,source_hz=48000,target_hz=22050):
    samples=struct.unpack('<'+'h'*(len(pcm)//2),pcm)
    count=round(len(samples)*target_hz/source_hz);cutoff=min(1,target_hz/source_hz)*.94
    result=[];radius=24
    for i in range(count):
        position=i*source_hz/target_hz;centre=math.floor(position);acc=total=0.
        for k in range(centre-radius+1,centre+radius+1):
            if not 0<=k<len(samples):continue
            x=position-k;t=x*cutoff
            sinc=1 if abs(t)<1e-10 else math.sin(math.pi*t)/(math.pi*t)
            window=.5+.5*math.cos(math.pi*x/radius) if abs(x)<=radius else 0
            weight=sinc*window*cutoff;acc+=samples[k]*weight;total+=weight
        sample=acc/total if total else 0
        result.append(sample)
    # Hardware FIFO A is already at 100%. Raise the quieter body of the sound
    # with a smooth limiter instead of clipping peaks or adding a second FIFO.
    peak=max((abs(v) for v in result),default=0) or 1
    drive=2.0;normalizer=127/math.tanh(drive)
    output=[]
    for i,v in enumerate(result):
        edge=min(1,i/(target_hz*.001),(count-1-i)/(target_hz*.001))
        output.append(round(normalizer*math.tanh(drive*v/peak)*edge)&255)
    return bytes(output)
def main():
    source=ROOT/'assets/slot/audio/insert-48000-s16.pcm';pcm=resample(source.read_bytes())
    out=ROOT/'common/slot_sounds.h'
    pad=pcm+b'\0'*((-len(pcm))%16)
    rows=['/* Slot insertion sound, GPL-3.0-or-later. Generated by tools/convert_sounds.py. */',
          'static const signed char slot_insert_pcm[] __attribute__((aligned(4))) = {']
    rows+=[' '+','.join(str(v if v<128 else v-256) for v in pad[i:i+24])+',' for i in range(0,len(pad),24)]
    rows+=['};',f'#define SLOT_INSERT_SAMPLES {len(pcm)}', '#define SLOT_SOUND_HZ 22050']
    out.write_text('\n'.join(rows)+'\n',encoding='utf-8')
    preview=ROOT/'preview/slot-insert.wav';preview.parent.mkdir(exist_ok=True)
    with wave.open(str(preview),'wb') as f:f.setnchannels(1);f.setsampwidth(1);f.setframerate(22050);f.writeframes(bytes(v^128 for v in pcm))
    (ROOT/'assets/slot/audio/conversion.json').write_text(json.dumps({'source_rate':48000,'source_format':'signed 16-bit LE mono','source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'output_rate':22050,'output_format':'signed 8-bit mono, 16-byte zero-padded DMA buffer','samples':len(pcm),'seconds':len(pcm)/22050,'smooth_limiter_drive':2.0,'output_peak':127,'edge_fade_ms':1,'eject_used':False},indent=2)+'\n',encoding='utf-8')
    print(len(pcm),'samples; duration',len(pcm)/22050,'; normalized signed-8 peak',max(abs(v if v<128 else v-256) for v in pcm))
if __name__=='__main__':main()
