"""Build redistributable fictional labels and a ROM-free rendering preview."""
from pathlib import Path
import io,sys,zipfile,json
from PIL import Image,ImageDraw,ImageFont
sys.path.insert(0,str(Path(__file__).parent))
from convert_labels import ROOT,ASSETS,convert
samples=ROOT/'examples';samples.mkdir(exist_ok=True)
font=ImageFont.truetype(str(ASSETS/'label.ttf'),90)
smallfont=ImageFont.truetype(str(ASSETS/'DejaVuSansMono.ttf'),24)
titles=[['ORBIT RUNNER','MOSS GARDEN','SKYLINE CIRCUIT'],['MOON POST','FOREST TRAIL','POCKET TIDES'],['PRISM QUEST','STAR SIGNAL','DEEP BLUE']]
colours=[['8855cc','438d48','d86338'],['b9ae8b','647c54','55a7ad'],['743ca3','cc4c8a','376eb3']]
with zipfile.ZipFile(samples/'slot-export.zip','w',zipfile.ZIP_STORED) as z:
    shells=[]
    for pi,platform in enumerate(('GBA','GB','GBC')):
        size=(1280,661) if platform=='GBA' else (1024,901)
        for i,title in enumerate(titles[pi]):
            bg=('#151a3b','#123b2b','#402945')[i]
            im=Image.new('RGB',size,bg);d=ImageDraw.Draw(im)
            for j in range(14):
                x=(j*113+i*71)%size[0];y=(j*67+i*41)%size[1]
                d.ellipse((x,y,x+10,y+10),fill='#f6d88d')
            if i==0:
                for r in range(210,70,-24):d.ellipse((size[0]*.52-r,size[1]*.50-r,size[0]*.52+r,size[1]*.50+r),outline='#e5a855',width=10)
                d.polygon([(size[0]*.35,size[1]*.32),(size[0]*.62,size[1]*.51),(size[0]*.42,size[1]*.60)],fill='#ece3c7')
            elif i==1:
                for j in range(5):
                    x=120+j*210;y=size[1]*.50
                    d.ellipse((x,y-145,x+180,y+20),fill='#58ac66')
                    d.rectangle((x+75,y,x+105,y+100),fill='#c8ad7b')
            else:
                for j in range(12):
                    x=j*115; y=size[1]*.55-(j%4)*55
                    d.rectangle((x,y,x+85,size[1]),fill=('#7756ab','#ac6aaf')[j%2])
                    for yy in range(int(y)+20,size[1]-40,55):d.rectangle((x+20,yy,x+35,yy+20),fill='#f2ca79')
            d.rectangle((0,0,size[0],65),fill='#e8e0c7')
            d.text((22,18),'slot. advance  /  '+platform,font=smallfont,fill='#2c2940')
            # Strong paper title band: remains legible at 1/3 scale.
            d.rectangle((0,size[1]-170,size[0],size[1]),fill='#ece4cd')
            f=font
            while d.textlength(title,font=f)>size[0]-50:f=ImageFont.truetype(str(ASSETS/'label.ttf'),f.size-2)
            d.text((size[0]/2,size[1]-86),title,font=f,anchor='mm',fill='#2b2840')
            buf=io.BytesIO();im.save(buf,format='PNG')
            z.writestr(f'Labels/{platform}/{title}.png',buf.getvalue())
            finish=('solid','clear','glitter')[i]
            outline='auto' if platform=='GBA' else ('notched' if platform=='GB' else 'rounded')
            shells.append(f'{title} = {outline} {colours[pi][i]} {finish}')
    z.writestr('Labels/cart_shell.txt','\n'.join(shells)+'\n')
manifest=convert(samples/'slot-export.zip',samples/'converted',previews=True)
header=['/* Fictional demo labels, no game ROMs. Generated by tools/make_examples.py. */']
for style in ('real','flat'):
    for pi,platform in enumerate(('GBA','GB','GBC')):
        for i,title in enumerate(titles[pi]):
            suffix='-flat' if style=='flat' else ''
            im=Image.open(samples/'converted/PREVIEWS'/platform/(title+suffix+'.png')).convert('RGBA')
            vals=[]
            for r,g,b,a in im.getdata():vals.append(0x8000 if a<128 else ((r>>3)|((g>>3)<<5)|((b>>3)<<10)))
            header.append(f'static const unsigned short demo_{style}_{pi}_{i}[{len(vals)}]={{')
            header+=[' '+','.join(f'0x{v:04x}' for v in vals[j:j+16])+',' for j in range(0,len(vals),16)]
            header.append('};')
    header.append('static const unsigned short *const demo_'+style+'[3][3]={'+','.join('{'+','.join(f'demo_{style}_{p}_{i}' for i in range(3))+'}' for p in range(3))+'};')
header.append('static const char *const demo_titles[3][3]='+json.dumps(titles).replace('[','{').replace(']','}')+';')
(ROOT/'tests/demo_assets.h').write_text('\n'.join(header)+'\n', encoding='utf-8')
print('Fictional sample export and cartridge assets ready')
